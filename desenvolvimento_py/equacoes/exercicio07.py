# 7) Qual número atende ao seguinte critério? Sua metade mais 7 é igual a 19.

# Equação:
# x/2 + 7 = 19
# x/2 = 19 - 7
# x/2 = 12
# x = 12 * 2
# x = 24

x = 24

resultado = (x / 2) + 7

if resultado == 19:
    print(f"O número que atende ao critério é: {x}")
else:
    print("O número não atende ao critério.")