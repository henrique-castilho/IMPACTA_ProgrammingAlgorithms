# 2) A diferença entre um número e sua terça parte é 20.
# Qual é esse número?

# Equação:
# x - x/3 = 20
# (3x - x)/3 = 20
# 2x/3 = 20
# 2x = 60
# x = 30

x = 30

diferenca = x - x/3
print(f"O número é: {x}")
print(f"Verificando a diferença: {x} - {x/3:} = {diferenca}")
print(f"Sua terça parte é: {x/3}")
