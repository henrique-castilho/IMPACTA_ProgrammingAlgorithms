# 6) A soma de dois números consecutivos é 47

# Seja x o primeiro número, então o segundo é x + 1

# Equação: 
# x + (x + 1) = 47
# 2x + 1 = 47
# 2x = 47 - 1
# 2x = 46
# x = 46 / 2
# x = 23

num1 = 23
num2 = num1 + 1

print(f"\nOs números consecutivos são: {num1} e {num2}")
print(f"Soma: {num1} + {num2} = {num1 + num2}")