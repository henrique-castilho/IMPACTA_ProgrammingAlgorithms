# Exemplo de números inteiros (int)
numero_inteiro = 11 + 10 + 1000
print(f"Valor inteiro: {numero_inteiro}")
print(f"Tipo: {type(numero_inteiro)}")
print()

# Exemplo de números decimais (float)
numero_decimal = 1.5 + 1 + 0.5
print(f"Valor decimal: {numero_decimal}")
print(f"Tipo: {type(numero_decimal)}")
print()

# Exemplo de valor booleano (bool)
valor_verdadeiro = True
valor_falso = False

print(f"Valor verdadeiro: {valor_verdadeiro}")
print(f"Tipo: {type(valor_verdadeiro)}")
print()

print(f"Valor falso: {valor_falso}")
print(f"Tipo: {type(valor_falso)}")
print()

# Exemplo de texto (string)
texto = "Python"
print(f"Texto: {texto}")
print(f"Tipo: {type(texto)}")