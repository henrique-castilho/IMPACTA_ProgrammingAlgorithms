# Criando a variável saldo e atribuindo o valor inicial 500
saldo = 500
print(saldo)  # Mostra o valor inicial do saldo


# Operador de adição com atribuição
# saldo += 10 é o mesmo que: saldo = saldo + 10
# Soma 10 ao valor atual de saldo
saldo +=10 
print(saldo)

# Operador de subtração com atribuição
# saldo -= 5 é o mesmo que: saldo = saldo - 5
# Subtrai 5 do valor atual de saldo
saldo -= 5
print(saldo)

# Operador de multiplicação com atribuição
# saldo *= 10 é o mesmo que: saldo = saldo * 10
# Multiplica o saldo atual por 10
saldo *= 10
print(saldo)

# Operador de divisão com atribuição
# saldo /= 2 é o mesmo que: saldo = saldo / 2
# Divide o saldo por 2 (resultado vira float)
saldo /= 2
print(saldo)

# Operador de divisão inteira com atribuição
# saldo //= 2 é o mesmo que: saldo = saldo // 2
# Divide por 2 e mantém apenas a parte inteira
saldo //= 2
print(saldo)

# Operador de módulo com atribuição
# saldo %= 4 é o mesmo que: saldo = saldo % 4
# Retorna o resto da divisão por 4
saldo %= 4
print(saldo)

# Operador de exponenciação com atribuição
# saldo **= 3 é o mesmo que: saldo = saldo ** 3
# Eleva o saldo à potência de 3 (saldo³)
saldo **= 3
print(saldo)