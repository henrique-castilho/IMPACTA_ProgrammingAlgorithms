produto_1 = 20
produto_2 = 3

# Soma
print(produto_1 + produto_2)

# Subtração
print(produto_1 - produto_2)

# Multiplicação
print(produto_1 * produto_2)

# Divisão com 2 casas decimais
print(f"{produto_1 / produto_2:.2f}")

# Divisão inteira (retorna apenas a parte inteira da divisão)
print(produto_1 // produto_2)

# Resto da divisão (módulo)
print(produto_1 % produto_2)

# Potência
print(produto_1 ** produto_2)

# Ordem de precedência: parênteses, exponenciação, multiplicação/divisão, adição/subtração
x = (10 + 5) * 4
y = (10 / 2) + 25 * ((2 - 2) ** 2)
print(x)
print(y)
